"""Pack a generated 2x8 flip sheet (row 1 front flip, row 2 back flip) for one Roman Arena fighter.
Usage (from the repo root):  python fight/tools/pack_flip.py SHEET.png FIGHTER_ID
- If the sheet has no real transparency, the white/paper background and its soft glow are keyed out.
- Frames are scaled so the standing landing pose (front flip frame 7) matches the fighter's in-game idle height.
- Every frame is anchored on its body centre, so the somersault turns around the middle of the body.
Writes fight/flips/<id>.webp and updates fight/flips/flip-data.js (window.__ARENA_FLIPS)."""
import sys, os, json, re
import numpy as np
from PIL import Image
from scipy import ndimage

src, fid = sys.argv[1], sys.argv[2]
ROOT = os.path.join(os.path.dirname(__file__), '..')
game = open(os.path.join(ROOT, 'game.js')).read(); dec = json.JSONDecoder()
def atlas(name): i = game.index('const ' + name + ' = ') + len('const ' + name + ' = '); return dec.raw_decode(game[i:])[0]

# ---- the fighter's in-game idle pose: height and body-centre offset above the feet ----
AA, FA = atlas('AATLAS'), atlas('FATLAS')
if fid == 'hades':
    im0 = np.array(Image.open(os.path.join(ROOT, 'hades-sprites-aligned.png')).convert('RGBA'))[0:220, 0:192, 3] > 40
else:
    a = AA.get('a_' + fid, {}); s, img = (a, f'atk/{fid}.webp') if 'idle' in a else (FA['f_' + fid], 'fighters.webp')
    x, y, w, h, ax, ay = s['idle'][0]; im0 = np.array(Image.open(os.path.join(ROOT, img)).convert('RGBA'))[y:y + h, x:x + w, 3] > 40
ys, _ = np.where(im0); IDLE_H = ys.max() - ys.min() + 1; IDLE_DY = ys.max() - ys.mean()

# ---- load, key out a fake background if needed ----
A = np.array(Image.open(src).convert('RGBA')).astype(int)
if (A[..., 3] < 10).mean() < 0.2:
    rgb = A[..., :3]; mx, mn = rgb.max(2), rgb.min(2)
    bgish = ((mx >= 205) & (mx - mn <= 22)) | (A[..., 3] < 30); lab, n = ndimage.label(bgish)
    edge = set(np.unique(np.concatenate([lab[0], lab[-1], lab[:, 0], lab[:, -1]]))) - {0}; bg = np.isin(lab, list(edge))
    for _ in range(4): bg = bg | (ndimage.binary_dilation(bg) & (mn >= 135) & (mx >= 190))
    A[..., 3] = np.where(bg, 0, 255)
A[..., 3][A[..., 3] < 24] = 0; A = A.astype(np.uint8)

# ---- find the 16 poses, grouped into 2 rows of 8 ----
m = A[..., 3] > 0; lab, n = ndimage.label(m, np.ones((3, 3)))
sizes = ndimage.sum(m, lab, range(1, n + 1)); objs = ndimage.find_objects(lab)
big = list(np.argsort(-sizes)[:16]); assert sizes[big[-1]] > sizes[big[0]] * 0.15, 'expected 16 poses'
cy = lambda k: (objs[k][0].start + objs[k][0].stop) / 2; cx = lambda k: (objs[k][1].start + objs[k][1].stop) / 2
big.sort(key=cy); rows = [sorted(big[:8], key=cx), sorted(big[8:], key=cx)]
groups = {k: [k] for k in big}
for k in range(n):   # loose bits (sparks, plume tips) join the nearest pose in the same row
    if k in groups or sizes[k] < 6: continue
    near = min(big, key=lambda b: (cx(b) - cx(k)) ** 2 + 4 * (cy(b) - cy(k)) ** 2); groups[near].append(k)

def cut(k):
    keep = np.isin(lab, [g + 1 for g in groups[k]]); ys, xs = np.where(keep)
    c = A[ys.min():ys.max() + 1, xs.min():xs.max() + 1].copy(); c[..., 3] = np.where(keep[ys.min():ys.max() + 1, xs.min():xs.max() + 1], c[..., 3], 0)
    return c
cells = [[cut(k) for k in r] for r in rows]
scale = IDLE_H / cells[0][6].shape[0]   # front-flip frame 7: standing tall as he lands

# ---- pack ----
PAD = 2; tiles, x, W, H, out = [], 0, 0, 0, {'front': [], 'back': []}
for name, row in zip(('front', 'back'), cells):
    x = 0; rh = 0
    for c in row:
        im = Image.fromarray(c); w, h = max(1, round(im.width * scale)), max(1, round(im.height * scale)); im = im.resize((w, h), Image.LANCZOS)
        al = np.array(im)[..., 3] > 40; yy, xx = np.where(al)
        tiles.append((im, x + PAD, H + PAD)); out[name].append([x + PAD, H + PAD, w, h, int(round(xx.mean())), int(round(yy.mean()))])
        x += w + PAD * 2; rh = max(rh, h + PAD * 2)
    W = max(W, x); H += rh
sheet = Image.new('RGBA', (W, H), (0, 0, 0, 0))
for im, px, py in tiles: sheet.alpha_composite(im, (px, py))
os.makedirs(os.path.join(ROOT, 'flips'), exist_ok=True)
sheet.save(os.path.join(ROOT, 'flips', fid + '.webp'), 'WEBP', quality=90, alpha_quality=92, method=6)

data_path = os.path.join(ROOT, 'flips', 'flip-data.js'); data = {}
if os.path.exists(data_path):
    t = open(data_path).read(); data = json.loads(t[t.index('{'):t.rindex('}') + 1])
data[fid] = {'dy': round(float(IDLE_DY), 1), 'front': out['front'], 'back': out['back']}
open(data_path, 'w').write('/* Generated by fight/tools/pack_flip.py: hand-drawn front/back flip frames, anchored on the body centre;\n   dy = how far that centre sits above the feet in the idle pose (in sheet pixels). */\nwindow.__ARENA_FLIPS = ' + json.dumps(data, separators=(',', ':')) + ';\n')
print(fid, 'scale %.3f' % scale, 'idle h', IDLE_H, 'dy %.1f' % IDLE_DY, 'sheet', W, 'x', H)
